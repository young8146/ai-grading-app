def norm(text):
    """자동 채점을 위한 기본 정규화"""
    if not text:
        return ""
    text = text.lower()
    text = re.sub(r"\s+", "", text)
    text = re.sub(r"[.,!?·:;()\[\]{}\"'“”‘’]", "", text)
    return text


def has_any(text, patterns):
    t = norm(text)
    return any(p in t for p in patterns)


def has_all(text, patterns):
    t = norm(text)
    return all(p in t for p in patterns)


def score_item(condition, reason, points):
    return {
        "score": points if condition else 0,
        "reason": reason
    }


