def grade_q1_set1(a):
    t = norm(a)
    checks = [
        any(x in t for x in ["쉬운", "큰노력을들일필요가없는", "노력이많이필요하지않"]),
        all(x in t for x in ["연습", "혼자"]) and any(x in t for x in ["익숙", "집중"]),
        "사회적억제" in t
    ]
    score = sum(checks)
    return score, checks


